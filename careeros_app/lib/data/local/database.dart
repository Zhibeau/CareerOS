// ── Database class ──

@DriftDatabase(tables: [
  Conversations,
  Projects,
  Skills,
  Achievements,
  Roles,
  ConversationProjects,
  ProjectSkills,
  ProjectAchievements,
])
class AppDatabase extends _$AppDatabase {
  AppDatabase() : super(_openConnection());

  AppDatabase.forTesting(super.e);

  @override
  int get schemaVersion => 1;

  // ── Conversations ──

  Future<bool> conversationExists(String convId) async {
    final row = await (select(conversations)
          ..where((c) => c.id.equals(convId)))
        .getSingleOrNull();
    return row != null;
  }

  Future<void> insertConversation(Conversation row) =>
      into(conversations).insertOnConflictUpdate(row);

  Future<void> updateIsWork(String convId, bool isWork) =>
      (update(conversations)..where((c) => c.id.equals(convId)))
          .write(ConversationsCompanion(isWork: Value(isWork ? 1 : 0)));

  // ── Skills (dedup by normalized name) ──

  Future<String> upsertSkill(Skill skill) async {
    final normalized = skill.name.trim().toLowerCase();
    final existing = await (select(skills)
          ..where((s) => s.name.equals(normalized)))
        .getSingleOrNull();
    if (existing != null) return existing.id;

    await into(skills).insert(SkillsCompanion.insert(
      id: skill.id,
      name: normalized,
      category: skill.category,
    ));
    return skill.id;
  }

  // ── Projects ──

  Future<String> upsertProject(Project project) async {
    final normalized = project.name.trim().toLowerCase();
    final existing = await (select(projects)
          ..where((p) => p.name.lower().equals(normalized)))
        .getSingleOrNull();
    if (existing != null) return existing.id;

    await into(projects).insert(ProjectsCompanion.insert(
      id: project.id,
      name: project.name,
      summary: Value(project.summary),
      status: Value(project.status),
      startedAt: Value(project.startedAt),
      endedAt: Value(project.endedAt),
      roleId: Value(project.roleId),
    ));
    return project.id;
  }

  Future<void> updateProject(ProjectsCompanion data) =>
      (update(projects)..where((p) => p.id.equals(data.id.value)))
          .write(data);

  // ── Achievements ──

  Future<String> insertAchievement(Achievement ach) async {
    await into(achievements).insert(AchievementsCompanion.insert(
      id: ach.id,
      summary: ach.summary,
      impact: Value(ach.impact),
      achievedAt: Value(ach.achievedAt),
    ));
    return ach.id;
  }

  // ── Roles ──

  Future<void> insertRole(Role role) =>
      into(roles).insert(RolesCompanion.insert(
        id: role.id,
        title: role.title,
        company: Value(role.company),
        startedAt: Value(role.startedAt),
        endedAt: Value(role.endedAt),
      ));

  Future<void> updateRole(RolesCompanion data) =>
      (update(roles)..where((r) => r.id.equals(data.id.value))).write(data);

  Future<void> linkProjectToRole(String projectId, String roleId) =>
      (update(projects)..where((p) => p.id.equals(projectId)))
          .write(ProjectsCompanion(roleId: Value(roleId)));

  // ── Junction tables ──

  Future<void> linkConversationProject(String convId, String projId) =>
      into(conversationProjects).insertOnConflictUpdate(
        ConversationProjectsCompanion.insert(
          conversationId: convId,
          projectId: projId,
        ),
      );

  Future<void> linkProjectSkill(String projId, String skillId) =>
      into(projectSkills).insertOnConflictUpdate(
        ProjectSkillsCompanion.insert(
          projectId: projId,
          skillId: skillId,
        ),
      );

  Future<void> linkProjectAchievement(String projId, String achId) =>
      into(projectAchievements).insertOnConflictUpdate(
        ProjectAchievementsCompanion.insert(
          projectId: projId,
          achievementId: achId,
        ),
      );

  // ── Queries ──

  Future<List<Project>> getAllProjects() async {
    final query = select(projects)
      ..orderBy([(p) => OrderingTerm.desc(p.startedAt)]);
    return query.get();
  }

  Future<List<Skill>> getAllSkills() =>
      (select(skills)..orderBy([(s) => OrderingTerm.asc(s.category),
        (s) => OrderingTerm.asc(s.name)])).get();

  Future<List<Achievement>> getAllAchievements() =>
      (select(achievements)
            ..orderBy([(a) => OrderingTerm.desc(a.achievedAt)]))
          .get();

  Future<List<Role>> getAllRoles() =>
      (select(roles)..orderBy([(r) => OrderingTerm.desc(r.startedAt)]))
          .get();

  Future<List<Project>> getProjectsForRole(String roleId) =>
      (select(projects)..where((p) => p.roleId.equals(roleId))).get();

  Future<List<Skill>> getSkillsForProject(String projectId) {
    final query = select(skills).join([
      innerJoin(
        projectSkills,
        projectSkills.skillId.equalsExp(skills.id),
      ),
    ])
      ..where(projectSkills.projectId.equals(projectId));

    return query.map((row) => row.readTable(skills)).get();
  }

  Future<void> deleteProject(String id) =>
      (delete(projects)..where((p) => p.id.equals(id))).go();

  Future<void> deleteSkill(String id) =>
      (delete(skills)..where((s) => s.id.equals(id))).go();

  Future<void> deleteAchievement(String id) =>
      (delete(achievements)..where((a) => a.id.equals(id))).go();

  Future<void> deleteRole(String id) =>
      (delete(roles)..where((r) => r.id.equals(id))).go();

  // ── Stats ──

  Future<Map<String, int>> getStats() async {
    final projectCount =
        await select(projects).get().then((r) => r.length);
    final skillCount =
        await select(skills).get().then((r) => r.length);
    final achievementCount =
        await select(achievements).get().then((r) => r.length);
    final roleCount =
        await select(roles).get().then((r) => r.length);
    return {
      'projects': projectCount,
      'skills': skillCount,
      'achievements': achievementCount,
      'roles': roleCount,
    };
  }
}

LazyDatabase _openConnection() {
  return LazyDatabase(() async {
    final dbFolder = await getApplicationDocumentsDirectory();
    final file = File(p.join(dbFolder.path, 'careeros.db'));
    return NativeDatabase.createInBackground(file);
  });
}
